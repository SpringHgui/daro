/// 把模板落成待插入正文：后续行跟随 `indent`，去掉 `{{}}` 只留参数名，
/// 返回每处参数的字节范围（相对正文起点，按出现顺序）。
pub fn render_template(template: &str, indent: &str) -> (String, Vec<std::ops::Range<usize>>) {
    let mut out = String::with_capacity(template.len());
    let mut stops = Vec::new();
    for (n, line) in template.split('\n').enumerate() {
        if n > 0 {
            out.push('\n');
            if !line.is_empty() {
                out.push_str(indent);
            }
        }
        let mut rest = line;
        while let Some(open) = rest.find("{{") {
            out.push_str(&rest[..open]);
            let Some(close) = rest[open + 2..].find("}}") else {
                out.push_str(&rest[open..]);
                rest = "";
                break;
            };
            let name = &rest[open + 2..open + 2 + close];
            let start = out.len();
            out.push_str(name);
            if !name.is_empty() {
                stops.push(start..out.len());
            }
            rest = &rest[open + 2 + close + 2..];
        }
        out.push_str(rest);
    }
    (out, stops)
}

/// 标签 + 搜索词过滤；搜索词对标题 / 说明 / 标签做大小写不敏感的子串匹配。
pub fn matches(item: &Snippet, needle: &str, tag: Option<&str>) -> bool {
    if tag.is_some_and(|t| item.tag != t) {
        return false;
    }
    let needle = needle.trim().to_lowercase();
    needle.is_empty()
        || item.title.to_lowercase().contains(&needle)
        || item.desc.to_lowercase().contains(&needle)
        || item.tag.to_lowercase().contains(&needle)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn render_template_strips_markers_and_reports_stop_ranges() {
        let (text, stops) = render_template("IF {{c}} THEN\n    {{s}}\nEND IF;", "");
        assert_eq!(text, "IF c THEN\n    s\nEND IF;");
        assert_eq!(stops, vec![3..4, 14..15]);
        assert_eq!(&text[stops[0].clone()], "c");
        assert_eq!(&text[stops[1].clone()], "s");
    }

    #[test]
    fn render_template_indents_following_lines_and_keeps_markers_in_order() {
        let (text, stops) = render_template("WHILE {{cond}} DO\n    {{body}}\nEND WHILE;", "  ");
        assert_eq!(text, "WHILE cond DO\n      body\n  END WHILE;");
        let names: Vec<&str> = stops.iter().map(|r| &text[r.clone()]).collect();
        assert_eq!(names, vec!["cond", "body"]);
    }

    #[test]
    fn every_snippet_has_a_complete_template_with_stops() {
        for item in ALL.iter() {
            let (text, stops) = render_template(item.template, "");
            assert!(!text.contains("{{") && !text.contains("}}"), "{}", item.title);
            assert!(!stops.is_empty(), "{} 没有参数占位", item.title);
            for r in stops {
                assert!(!text[r].trim().is_empty(), "{} 有空占位", item.title);
            }
        }
    }
}
