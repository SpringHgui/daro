//! 查询工具栏「代码段」右侧面板的数据：条目与说明按通用 SQL 与过程化语法整理
//! （CASE / COMMENTS / ... / WHILE）。
//! 两条专有语法（结果页签名、运行参数）daro 还不支持，插入的是写明这一点的
//! 注释占位，不伪造语义。
//!
//! 模板里的 `{{name}}` 是参数占位：插入时去掉花括号只留 name，并记下每处
//! 的字节范围（见 [`render_template`]）。界面据此标绿底，Tab 依次跳过去。

pub struct Snippet {
    pub title: &'static str,
    pub tag: &'static str,
    pub desc: &'static str,
    pub template: &'static str,
}

